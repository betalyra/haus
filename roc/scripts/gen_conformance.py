#!/usr/bin/env python3
"""Generate roc/package/ConformanceTest.roc from the shared test-suite.

Each fixture is embedded with `import "…" as name : List(U8)`, so `roc test`
runs the suite without a platform. Re-run after changing test-suite/.
"""
import json
import subprocess
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUITE = ROOT / "test-suite"
OUT = ROOT / "roc" / "package" / "ConformanceTest.roc"


def ident(kind: str, name: str) -> str:
    return f"{kind}_{re.sub(r'[^a-z0-9]', '_', name.lower())}"


BIDI = re.compile("[\u202a-\u202e\u2066-\u2069\x7f-\x9f]")


def roc_str(s: str) -> str:
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    # Roc (like haus) rejects raw bidi and control characters in source; write them as escapes.
    s = BIDI.sub(lambda m: f"\\u({ord(m.group()):04X})", s)
    return '"' + s + '"'


imports, tests = [], []
for path in sorted((SUITE / "valid").glob("*.haus")):
    name = ident("valid", path.stem)
    expected = json.loads(path.with_suffix(".json").read_text(encoding="utf-8"))
    imports.append(f'import "../../test-suite/valid/{path.name}" as {name} : List(U8)')
    tests.append(f"# valid/{path.name}\nexpect ConformanceTest.run({name}) == {roc_str(json.dumps(expected, ensure_ascii=False, separators=(',', ':')))}")
for path in sorted((SUITE / "invalid").glob("*.haus")):
    name = ident("invalid", path.stem)
    imports.append(f'import "../../test-suite/invalid/{path.name}" as {name} : List(U8)')
    tests.append(f"# invalid/{path.name}\nexpect ConformanceTest.rejects({name})")

OUT.write_text(
    "# GENERATED by roc/scripts/gen_conformance.py from test-suite/. Do not edit.\n"
    "import Value\n"
    + "\n".join(imports)
    + """

ConformanceTest := [].{
    ## The parsed values in the suite's JSON form, or the error.
    run : List(U8) -> Str
    run = |bytes| match Value.parse_bytes(bytes) {
        Ok(values) => "[${Str.join_with(values.map(Value.to_test_json), ",")}]"
        Err({ reason, line, column }) => "ERROR ${reason} at ${line.to_str()}:${column.to_str()}"
    }

    rejects : List(U8) -> Bool
    rejects = |bytes| match Value.parse_bytes(bytes) {
        Ok(_) => False
        Err(_) => True
    }
}

"""
    + "\n\n".join(tests)
    + "\n",
    encoding="utf-8",
)
subprocess.run(["roc", "fmt", str(OUT)], check=True, capture_output=True)
print(f"wrote {OUT.relative_to(ROOT)}: {len(tests)} tests")
