//! Rust code from a schema: one item per named type, with `Decode` and
//! `Encode` implementations that check every rule of the schema.
//!
//! | haus                         | Rust                                     |
//! |------------------------------|------------------------------------------|
//! | `{ a: T, b?: U }`            | `struct { a: T, b: Option<U> }`          |
//! | `< A \| B T \| C { … } >`    | `enum { A, B(T), C { … }, Unknown(…) }`  |
//! | `closed < Tag T U >`         | `struct Tag(T, U)`                       |
//! | `< >`                        | `haus::AnyTag`                           |
//! | `Maybe a`, `Result e a`      | `Option<A>`, `Result<A, E>`              |
//! | `Array a`, `Map v`           | `Vec<A>`, `BTreeMap<String, V>`          |
//! | `Any`, `Secret a`            | `haus::Value`, `haus::Secret<A>`         |
//!
//! `@deprecated` types, fields and tags get `#[deprecated]`. The generated
//! code itself allows their use, so only code that touches them is warned.
//!
//! Records and variants written inline get a name from where they are:
//! `Order.status` becomes `OrderStatus`. The code is built as tokens with
//! `quote!` and printed with `prettyplease`.

use crate::schema::{Attribute, Case, Error, Field, File, PRELUDE, Ty, TypeDef, deprecation, error};
use proc_macro2::{Ident, Literal, Span, TokenStream};
use quote::{ToTokens, format_ident, quote};
use std::collections::{HashMap, HashSet};

/// A type imported from std/time or a schema package.
#[derive(Debug, Clone)]
pub struct Imported {
    /// `std/time#Date`, `@haus/money@1#Money`.
    pub id: String,
    /// The Rust path: `::haus::time::Date`, `::haus_money::Money`.
    pub path: String,
    pub params: usize,
}

/// A codec: the Rust type (implementing `haus::Codec`) used for the type with this id.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Codec {
    /// `@haus/money@1#Money`.
    pub id: String,
    /// `crate::codecs::Cents`.
    pub path: String,
}

pub struct Input<'a> {
    pub text: &'a str,
    /// The file's id: `@haus/money@1`, `order-app/src/order`.
    pub id: &'a str,
    /// Imported types by name.
    pub imports: &'a HashMap<String, Imported>,
    pub codecs: &'a [Codec],
}

pub const STD_TIME: [&str; 8] =
    ["Date", "Time", "DateTime", "Instant", "ZonedDateTime", "Duration", "YearMonth", "TimeZone"];

pub fn generate(file: &File, input: &Input) -> Result<String, Error> {
    let fail = |pos, reason: String| Err(error(input.text, pos, reason));
    let ids = known_ids(file, input);
    if let Some(codec) = input.codecs.iter().find(|c| !ids.contains(&c.id)) {
        return fail(
            0,
            format!("a codec for {}, but the schema has no such type (it has {})", codec.id, ids.join(", ")),
        );
    }
    let codecs = input
        .codecs
        .iter()
        .map(|c| {
            Ok((
                c.id.as_str(),
                rust_path(&c.path).ok_or_else(|| error(input.text, 0, format!("{} is not a Rust path", c.path)))?,
            ))
        })
        .collect::<Result<HashMap<_, _>, Error>>()?;

    let defs: HashMap<&str, &TypeDef> = file.types.iter().map(|d| (d.name.as_str(), d)).collect();
    let mut g = Gen {
        input,
        reach: reach(&defs),
        defs,
        names: file.types.iter().map(|d| d.name.clone()).collect(),
        codecs,
        items: vec![],
    };
    file.types.iter().try_for_each(|def| g.define_named(def))?;

    let checks = g.codecs.iter().map(|(id, path)| {
        let message = format!("{path} is a codec for another type than {id}");
        quote! {
            const _: () = ::core::assert!(::haus::same_id(<#path as ::haus::Codec>::ID, #id), #message);
        }
    });
    let items = &g.items;
    let tokens = quote! { #(#items)* #(#checks)* };
    let code = syn::parse2::<syn::File>(tokens)
        .map_err(|e| error(input.text, 0, format!("haus-build generated invalid Rust: {e}")))?;
    Ok(format!("// Generated by haus-build from {}. Don't edit.\n\n{}", input.id, prettyplease::unparse(&code)))
}

/// Every id a codec could target: this file's types and the imported ones.
fn known_ids(file: &File, input: &Input) -> Vec<String> {
    let own = file.types.iter().map(|d| format!("{}#{}", input.id, d.name));
    own.chain(input.imports.values().map(|i| i.id.clone())).collect()
}

/// A Rust path or type, as written in a codec or an import: `crate::codecs::Cents`.
fn rust_path(path: &str) -> Option<TokenStream> {
    syn::parse_str::<syn::Type>(path).ok().map(|t| quote!(#t))
}

// ── recursion ────────────────────────────────────────────────

/// The types each type contains directly (not behind an array or map), transitively.
/// A reference from `a` to `b` needs a `Box` if `b` reaches `a`.
fn reach<'a>(defs: &HashMap<&'a str, &'a TypeDef>) -> HashMap<&'a str, HashSet<&'a str>> {
    fn direct<'a>(ty: &'a Ty, out: &mut HashSet<&'a str>) {
        match ty {
            Ty::Name { name, .. } if matches!(name.as_str(), "Array" | "Map") => {}
            Ty::Name { name, args, .. } => {
                out.insert(name);
                for a in args {
                    direct(a, out);
                }
            }
            Ty::Param { .. } => {}
            Ty::Record { fields, .. } => fields.iter().for_each(|f| direct(&f.ty, out)),
            Ty::Variant { cases, .. } => cases.iter().flat_map(|c| &c.payload).for_each(|t| direct(t, out)),
        }
    }
    let edges: HashMap<&str, HashSet<&str>> = defs
        .iter()
        .map(|(&name, def)| {
            let mut out = HashSet::new();
            direct(&def.ty, &mut out);
            (name, out.into_iter().filter(|n| defs.contains_key(n)).collect())
        })
        .collect();
    let reachable = |start: &str| {
        let mut seen = HashSet::new();
        let mut stack: Vec<&str> = edges[start].iter().copied().collect();
        while let Some(n) = stack.pop() {
            if seen.insert(n) {
                stack.extend(&edges[n]);
            }
        }
        seen
    };
    edges.keys().map(|&start| (start, reachable(start))).collect()
}

// ── Rust types and their (de)coding ──────────────────────────

/// Decoding or encoding a value `x`: a function to call, or an expression in `x`.
#[derive(Clone)]
enum Fun {
    Path(TokenStream),
    Expr(TokenStream),
}

impl Fun {
    /// As a function value: `f`, or `|x| expr`.
    fn value(&self) -> TokenStream {
        match self {
            Fun::Path(f) => f.clone(),
            Fun::Expr(e) => quote!(|x| #e),
        }
    }

    /// Applied to `arg`.
    fn call(&self, arg: TokenStream) -> TokenStream {
        match self {
            Fun::Path(f) => quote!(#f(#arg)),
            Fun::Expr(e) => quote!({ let x = #arg; #e }),
        }
    }
}

/// A Rust type, how to decode it from `x: &Value`, and how to encode `x: &T`.
struct Rs {
    ty: TokenStream,
    de: Fun,
    en: Fun,
}

impl Rs {
    /// A type that implements `Decode` and `Encode` itself.
    fn plain(ty: TokenStream) -> Rs {
        Rs { de: Fun::Path(quote!(<#ty as ::haus::Decode>::decode)), en: Fun::Path(quote!(::haus::Encode::encode)), ty }
    }

    /// A container with helpers `::haus::de::<helper>` and `::haus::ser::<helper>`.
    fn container(ty: TokenStream, helper: &str, items: &[&Rs]) -> Rs {
        let helper = format_ident!("{helper}");
        let (de, en): (Vec<_>, Vec<_>) = items.iter().map(|r| (r.de.value(), r.en.value())).unzip();
        Rs {
            ty,
            de: Fun::Expr(quote!(::haus::de::#helper(x, #(#de),*))),
            en: Fun::Expr(quote!(::haus::ser::#helper(x, #(#en),*))),
        }
    }

    fn boxed(self) -> Rs {
        let (ty, de) = (self.ty, self.de.call(quote!(x)));
        Rs {
            ty: quote!(::std::boxed::Box<#ty>),
            de: Fun::Expr(quote!(#de.map(::std::boxed::Box::new))),
            en: Fun::Expr(self.en.call(quote!(&**x))),
        }
    }
}

/// A field of a struct or a struct-like variant.
struct FieldRs {
    name: Ident,
    key: String,
    optional: bool,
    rs: Rs,
    /// `#[deprecated]`, or nothing.
    deprecated: TokenStream,
}

impl FieldRs {
    fn decl(&self, visibility: TokenStream) -> TokenStream {
        let (name, ty, deprecated) = (&self.name, &self.rs.ty, &self.deprecated);
        if self.optional {
            quote!(#deprecated #visibility #name: ::std::option::Option<#ty>)
        } else {
            quote!(#deprecated #visibility #name: #ty)
        }
    }

    /// `name: r.required("key", decode)?`.
    fn de(&self) -> TokenStream {
        let (name, key, f) = (&self.name, &self.key, self.rs.de.value());
        let how = format_ident!("{}", if self.optional { "optional" } else { "required" });
        quote!(#name: r.#how(#key, #f)?)
    }

    /// The entry for `ser::record`: `place` is the field (`self.name`), or a
    /// reference to it when `bound` by a pattern (`name`).
    fn en(&self, place: TokenStream, bound: bool) -> TokenStream {
        let key = &self.key;
        if self.optional {
            let f = self.rs.en.value();
            quote!((#key, #place.as_ref().map(#f)))
        } else {
            let value = self.rs.en.call(if bound { place } else { quote!(&#place) });
            quote!((#key, ::std::option::Option::Some(#value)))
        }
    }
}

/// The payload of a case, in Rust.
enum Payload<'a> {
    None,
    Tuple(Vec<Rs>),
    Record { closed: bool, fields: &'a [Field], rs: Vec<FieldRs> },
}

// ── generation ───────────────────────────────────────────────

struct Gen<'a> {
    input: &'a Input<'a>,
    defs: HashMap<&'a str, &'a TypeDef>,
    reach: HashMap<&'a str, HashSet<&'a str>>,
    codecs: HashMap<&'a str, TokenStream>,
    /// Names of generated types, so names for inline types don't clash.
    names: HashSet<String>,
    items: Vec<TokenStream>,
}

/// Where a type expression is: in which definition, and what an inline type there is called.
#[derive(Clone)]
struct At<'a> {
    owner: &'a TypeDef,
    hint: String,
    /// Behind an array or a map: no `Box` needed.
    contained: bool,
}

impl<'a> At<'a> {
    fn inner(&self, suffix: &str) -> At<'a> {
        At { hint: format!("{}{}", self.hint, pascal(suffix)), ..self.clone() }
    }

    fn contained(&self) -> At<'a> {
        At { contained: true, ..self.clone() }
    }
}

/// A type being defined: its name, generics and documentation.
struct Item<'a> {
    name: Ident,
    params: Vec<Ident>,
    /// Doc comments, and `#[deprecated]` if it is.
    doc: TokenStream,
    at: At<'a>,
}

impl Item<'_> {
    /// `<A, B>`.
    fn generics(&self) -> TokenStream {
        let params = &self.params;
        if params.is_empty() { quote!() } else { quote!(<#(#params),*>) }
    }

    /// `<A: ::haus::<bound>, …>`.
    fn bounded(&self, bound: &str) -> TokenStream {
        let (params, bound) = (&self.params, format_ident!("{bound}"));
        if params.is_empty() { quote!() } else { quote!(<#(#params: ::haus::#bound),*>) }
    }

    /// The type definition, and its `Decode` and `Encode` implementations.
    fn implement(&self, definition: TokenStream, decode: TokenStream, encode: TokenStream) -> TokenStream {
        let (doc, name, g) = (&self.doc, &self.name, self.generics());
        let (de_g, en_g) = (self.bounded("Decode"), self.bounded("Encode"));
        quote! {
            #doc
            #[derive(Debug, Clone, PartialEq)]
            #[allow(deprecated)]
            #definition

            #[allow(deprecated)]
            impl #de_g ::haus::Decode for #name #g {
                fn decode(v: &::haus::Value) -> ::std::result::Result<Self, ::haus::DecodeError> {
                    #decode
                }
            }

            #[allow(deprecated)]
            impl #en_g ::haus::Encode for #name #g {
                fn encode(&self) -> ::haus::Value {
                    #encode
                }
            }
        }
    }
}

impl<'a> Gen<'a> {
    fn fail<T>(&self, pos: usize, reason: impl Into<String>) -> Result<T, Error> {
        Err(error(self.input.text, pos, reason))
    }

    fn define_named(&mut self, def: &'a TypeDef) -> Result<(), Error> {
        // A stream is a file of values, read with `haus::from_str_all`: no type of its own.
        if let Ty::Name { name, args, pos } = &def.ty
            && name == "Stream"
        {
            return match args.as_slice() {
                [Ty::Name { .. }] => Ok(()),
                _ => self.fail(*pos, "Stream takes one named type: type Events = Stream Event"),
            };
        }
        let id = format!("{}#{}", self.input.id, def.name);
        let item = Item {
            name: format_ident!("{}", def.name),
            params: def.params.iter().map(|p| param(p)).collect(),
            doc: {
                let doc = docs(def.doc.lines().chain(["", &format!("haus type `{id}`.")]).skip_while(|l| l.is_empty()));
                let deprecated = deprecated(&def.attrs);
                quote!(#doc #deprecated)
            },
            at: At { owner: def, hint: def.name.clone(), contained: false },
        };
        self.define(&item, &def.ty, Some(&id))
    }

    /// The item for a type, with its id if it has one.
    fn define(&mut self, item: &Item<'a>, ty: &'a Ty, id: Option<&str>) -> Result<(), Error> {
        let (doc, name, g) = (&item.doc, &item.name, item.generics());
        let (code, nominal) = match ty {
            Ty::Record { closed, fields, .. } => (self.record(item, *closed, fields)?, true),
            Ty::Variant { closed: false, cases, .. } if cases.is_empty() => {
                (quote! { #doc pub type #name #g = ::haus::AnyTag; }, false)
            }
            Ty::Variant { closed: true, cases, .. } if cases.len() == 1 => (self.single(item, &cases[0])?, true),
            Ty::Variant { closed, cases, .. } => (self.variant(item, *closed, cases)?, true),
            ty => {
                let target = self.lower(ty, &item.at)?.ty;
                (quote! { #doc #[allow(deprecated)] pub type #name #g = #target; }, false)
            }
        };
        // Structs and enums carry their id; aliases can't.
        let id = id.filter(|_| nominal).map(|id| {
            quote! {
                #[allow(deprecated)]
                impl #g #name #g {
                    /// The type's id (spec §13.3).
                    #[allow(dead_code)]
                    pub const ID: &'static str = #id;
                }
            }
        });
        self.items.push(quote! { #code #id });
        Ok(())
    }

    /// A Rust type for a type expression.
    fn lower(&mut self, ty: &'a Ty, at: &At<'a>) -> Result<Rs, Error> {
        match ty {
            Ty::Param { name, .. } if at.owner.params.contains(name) => {
                let p = param(name);
                Ok(Rs::plain(quote!(#p)))
            }
            Ty::Param { name, pos } => self.fail(*pos, format!("unknown type parameter {name}")),
            Ty::Record { .. } | Ty::Variant { .. } => self.inline(ty, at),
            Ty::Name { name, args, pos } => self.named(name, args, *pos, at),
        }
    }

    fn named(&mut self, name: &str, args: &'a [Ty], pos: usize, at: &At<'a>) -> Result<Rs, Error> {
        let arity = |params: usize| {
            (args.len() != params).then(|| format!("{name} takes {params} argument(s), found {}", args.len()))
        };
        let (id, path, params) = if let Some(def) = self.defs.get(name) {
            let ident = format_ident!("{name}");
            (format!("{}#{name}", self.input.id), quote!(#ident), def.params.len())
        } else if let Some(imp) = self.input.imports.get(name) {
            let path = rust_path(&imp.path)
                .ok_or_else(|| error(self.input.text, pos, format!("{} is not a Rust path", imp.path)))?;
            (imp.id.clone(), path, imp.params)
        } else if let Some(&(_, params)) = PRELUDE.iter().find(|(n, _)| *n == name) {
            return match arity(params) {
                Some(reason) => self.fail(pos, reason),
                None => self.prelude(name, args, pos, at),
            };
        } else {
            let hint = match name {
                "Money" | "Currency" => format!(" (import it with: import @haus/money ({name}))"),
                _ if STD_TIME.contains(&name) => format!(" (import it with: import std/time ({name}))"),
                _ => String::new(),
            };
            return self.fail(pos, format!("unknown type {name}{hint}"));
        };
        if let Some(reason) = arity(params) {
            return self.fail(pos, reason);
        }
        if let Some(codec) = self.codecs.get(id.as_str()).filter(|_| args.is_empty()) {
            return Ok(Rs {
                ty: quote!(<#codec as ::haus::Codec>::Target),
                de: Fun::Path(quote!(::haus::de::codec::<#codec>)),
                en: Fun::Path(quote!(::haus::ser::codec::<#codec>)),
            });
        }
        let args = args.iter().map(|a| self.lower(a, at).map(|r| r.ty)).collect::<Result<Vec<_>, _>>()?;
        let rs = Rs::plain(if args.is_empty() { path } else { quote!(#path<#(#args),*>) });
        let recursive = self.reach.get(name).is_some_and(|r| r.contains(at.owner.name.as_str()));
        Ok(if recursive && !at.contained { rs.boxed() } else { rs })
    }

    fn prelude(&mut self, name: &str, args: &'a [Ty], pos: usize, at: &At<'a>) -> Result<Rs, Error> {
        let scalar = |ty: TokenStream| Ok(Rs::plain(ty));
        match name {
            "Bool" => scalar(quote!(bool)),
            "String" => scalar(quote!(::std::string::String)),
            "Bytes" => scalar(quote!(::haus::Bytes)),
            "Int" => scalar(quote!(::haus::Int)),
            "Decimal" => scalar(quote!(::haus::Decimal)),
            "Int8" | "Int16" | "Int32" | "Int64" => scalar(format_ident!("i{}", &name[3..]).into_token_stream()),
            "UInt8" | "UInt16" | "UInt32" | "UInt64" => scalar(format_ident!("u{}", &name[4..]).into_token_stream()),
            "Float32" | "Float64" => scalar(format_ident!("f{}", &name[5..]).into_token_stream()),
            "Any" => scalar(quote!(::haus::Value)),
            "Secret" => {
                let inner = self.lower(&args[0], at)?;
                let (ty, de, en) = (&inner.ty, inner.de.value(), inner.en.value());
                let what = format!("Secret {}", args[0]);
                Ok(Rs {
                    ty: quote!(::haus::Secret<#ty>),
                    de: Fun::Expr(quote!(::haus::de::secret(x, #what, #de))),
                    en: Fun::Expr(quote!(::haus::ser::secret(x, #en))),
                })
            }
            "Array" => {
                let item = self.lower(&args[0], &at.inner("Item").contained())?;
                let ty = &item.ty;
                Ok(Rs::container(quote!(::std::vec::Vec<#ty>), "array", &[&item]))
            }
            "Map" => {
                let value = self.lower(&args[0], &at.inner("Value").contained())?;
                let ty = &value.ty;
                Ok(Rs::container(quote!(::std::collections::BTreeMap<::std::string::String, #ty>), "map", &[&value]))
            }
            "Maybe" => {
                let some = self.lower(&args[0], at)?;
                let ty = &some.ty;
                Ok(Rs::container(quote!(::std::option::Option<#ty>), "maybe", &[&some]))
            }
            "Result" => {
                let (err, ok) = (self.lower(&args[0], &at.inner("Err"))?, self.lower(&args[1], &at.inner("Ok"))?);
                let (e, a) = (&err.ty, &ok.ty);
                Ok(Rs::container(quote!(::std::result::Result<#a, #e>), "result", &[&ok, &err]))
            }
            _ => self.fail(pos, format!("{name} is only allowed as the whole type of a definition")),
        }
    }

    /// A record or variant written inline: a type of its own, named after where it is.
    fn inline(&mut self, ty: &'a Ty, at: &At<'a>) -> Result<Rs, Error> {
        let name = at.hint.clone();
        if !self.names.insert(name.clone()) {
            return self.fail(
                ty.pos(),
                format!("the inline type here would be called {name}, which is taken; give it a name"),
            );
        }
        let mut used = HashSet::new();
        params_in(ty, &mut used);
        let item = Item {
            name: format_ident!("{name}"),
            params: at.owner.params.iter().filter(|p| used.contains(p.as_str())).map(|p| param(p)).collect(),
            doc: docs([format!("`{name}`, inline in {}.", at.owner.name).as_str()].into_iter()),
            at: At { hint: name, ..at.clone() },
        };
        self.define(&item, ty, None)?;
        let (ident, g) = (&item.name, item.generics());
        Ok(Rs::plain(quote!(#ident #g)))
    }

    fn fields(&mut self, fields: &'a [Field], at: &At<'a>) -> Result<Vec<FieldRs>, Error> {
        let out = fields
            .iter()
            .map(|f| {
                let rs = self.lower(&f.ty, &at.inner(&f.key))?;
                Ok(FieldRs {
                    name: field_ident(&f.key),
                    key: f.key.clone(),
                    optional: f.optional,
                    rs,
                    deprecated: deprecated(&f.attrs),
                })
            })
            .collect::<Result<Vec<_>, Error>>()?;
        match out.iter().enumerate().find(|(i, f)| out[..*i].iter().any(|g| g.name == f.name)) {
            Some((i, f)) => {
                self.fail(fields[i].pos, format!("fields {} and another one are both {} in Rust", f.key, f.name))
            }
            None => Ok(out),
        }
    }

    fn payload(&mut self, case: &'a Case, at: &At<'a>) -> Result<Payload<'a>, Error> {
        let at = at.inner(&case.tag);
        Ok(match case.payload.as_slice() {
            [] => Payload::None,
            [Ty::Record { closed, fields, .. }] => {
                Payload::Record { closed: *closed, fields, rs: self.fields(fields, &at)? }
            }
            [one] => Payload::Tuple(vec![self.lower(one, &at)?]),
            items => Payload::Tuple(
                items
                    .iter()
                    .enumerate()
                    .map(|(i, t)| self.lower(t, &at.inner(&i.to_string())))
                    .collect::<Result<_, _>>()?,
            ),
        })
    }

    /// `{ … }`: a struct.
    fn record(&mut self, item: &Item<'a>, closed: bool, fields: &'a [Field]) -> Result<TokenStream, Error> {
        let fs = self.fields(fields, &item.at)?;
        let (name, g, label) = (&item.name, item.generics(), item.name.to_string());
        let decls = fs.iter().map(|f| f.decl(quote!(pub)));
        let decoded = fs.iter().map(FieldRs::de);
        let entries = fs.iter().map(|f| {
            let n = &f.name;
            f.en(quote!(self.#n), false)
        });
        let bind = bind_record(quote!(::haus::de::Record::new(v, #label)), closed, fields);
        Ok(item.implement(
            quote!(pub struct #name #g { #(#decls),* }),
            quote! {
                #bind
                ::std::result::Result::Ok(Self { #(#decoded),* })
            },
            quote!(::haus::ser::record([#(#entries),*])),
        ))
    }

    /// `closed < Tag … >`: a struct, checked for its tag.
    fn single(&mut self, item: &Item<'a>, case: &'a Case) -> Result<TokenStream, Error> {
        let (name, g, label, tag) = (&item.name, item.generics(), item.name.to_string(), &case.tag);
        let (definition, decode, encode) = match self.payload(case, &item.at)? {
            Payload::None => (
                quote!(pub struct #name;),
                quote! {
                    ::haus::de::args::<0>(tag, args)?;
                    ::std::result::Result::Ok(Self)
                },
                quote!(::haus::ser::variant(#tag, ::std::vec![])),
            ),
            Payload::Tuple(items) => {
                let tys = items.iter().map(|r| &r.ty);
                let (bind, values) = tuple_de(&items);
                let vars = vars(items.len());
                let encoded = tuple_en(&items);
                (
                    quote!(pub struct #name #g (#(pub #tys),*);),
                    quote! { #bind ::std::result::Result::Ok(Self(#(#values),*)) },
                    quote! {
                        let Self(#(#vars),*) = self;
                        ::haus::ser::variant(#tag, ::std::vec![#(#encoded),*])
                    },
                )
            }
            Payload::Record { closed, fields, rs } => {
                let decls = rs.iter().map(|f| f.decl(quote!(pub)));
                let decoded = rs.iter().map(FieldRs::de);
                let entries = rs.iter().map(|f| {
                    let n = &f.name;
                    f.en(quote!(self.#n), false)
                });
                let bind = bind_record(quote!(::haus::de::payload(tag, args)), closed, fields);
                (
                    quote!(pub struct #name #g { #(#decls),* }),
                    quote! {
                        #bind
                        ::std::result::Result::Ok(Self { #(#decoded),* })
                    },
                    quote!(::haus::ser::variant(#tag, ::std::vec![::haus::ser::record([#(#entries),*])])),
                )
            }
        };
        let deprecated = deprecated(&case.attrs);
        Ok(item.implement(
            quote!(#deprecated #definition),
            quote! {
                let (tag, args) = ::haus::de::variant(v, #label)?;
                if tag != #tag {
                    return ::std::result::Result::Err(::haus::de::unknown_tag(tag, &[#tag]));
                }
                #decode
            },
            encode,
        ))
    }

    /// `< A | B T | C { … } >`: an enum, with `Unknown` for other tags if it's open.
    fn variant(&mut self, item: &Item<'a>, closed: bool, cases: &'a [Case]) -> Result<TokenStream, Error> {
        if let Some(case) = cases.iter().find(|c| !closed && c.tag == "Unknown") {
            return self.fail(
                case.pos,
                "an open variant can't have a tag Unknown in Rust (unknown tags decode to Unknown); close it",
            );
        }
        let (name, g, label) = (&item.name, item.generics(), item.name.to_string());
        let arms = cases
            .iter()
            .map(|case| {
                let (tag, v) = (&case.tag, format_ident!("{}", case.tag));
                let deprecated = deprecated(&case.attrs);
                Ok(match self.payload(case, &item.at)? {
                    Payload::None => (
                        quote!(#deprecated #v),
                        quote!(#tag => { ::haus::de::args::<0>(tag, args)?; ::std::result::Result::Ok(Self::#v) }),
                        quote!(Self::#v => ::haus::ser::variant(#tag, ::std::vec![])),
                    ),
                    Payload::Tuple(items) => {
                        let tys = items.iter().map(|r| &r.ty);
                        let (bind, values) = tuple_de(&items);
                        let vars = vars(items.len());
                        let encoded = tuple_en(&items);
                        (
                            quote!(#deprecated #v(#(#tys),*)),
                            quote!(#tag => { #bind ::std::result::Result::Ok(Self::#v(#(#values),*)) }),
                            quote!(Self::#v(#(#vars),*) => ::haus::ser::variant(#tag, ::std::vec![#(#encoded),*])),
                        )
                    }
                    Payload::Record { closed, fields, rs } => {
                        let decls = rs.iter().map(|f| f.decl(quote!()));
                        let decoded = rs.iter().map(FieldRs::de);
                        let names = rs.iter().map(|f| &f.name);
                        let entries = rs.iter().map(|f| {
                            let n = &f.name;
                            f.en(quote!(#n), true)
                        });
                        let bind = bind_record(quote!(::haus::de::payload(tag, args)), closed, fields);
                        (
                            quote!(#deprecated #v { #(#decls),* }),
                            quote!(#tag => {
                                #bind
                                ::std::result::Result::Ok(Self::#v { #(#decoded),* })
                            }),
                            quote!(Self::#v { #(#names),* } => ::haus::ser::variant(#tag, ::std::vec![::haus::ser::record([#(#entries),*])])),
                        )
                    }
                })
            })
            .collect::<Result<Vec<_>, Error>>()?;
        let (decls, (decode, encode)): (Vec<_>, (Vec<_>, Vec<_>)) =
            arms.into_iter().map(|(d, de, en)| (d, (de, en))).unzip();
        let tags = cases.iter().map(|c| &c.tag);
        let (other_decl, other_de, other_en) = if closed {
            (quote!(), quote!(_ => ::std::result::Result::Err(::haus::de::unknown_tag(tag, &[#(#tags),*]))), quote!())
        } else {
            (
                quote! {
                    /// A tag this schema doesn't list, kept as it was.
                    Unknown(::haus::Unknown),
                },
                quote!(_ => ::std::result::Result::Ok(Self::Unknown(::haus::Unknown::new(tag, args)))),
                quote!(Self::Unknown(u) => ::haus::Encode::encode(u),),
            )
        };
        Ok(item.implement(
            quote!(pub enum #name #g { #(#decls,)* #other_decl }),
            quote! {
                let (tag, args) = ::haus::de::variant(v, #label)?;
                match tag {
                    #(#decode)*
                    #other_de
                }
            },
            quote! {
                match self {
                    #(#encode,)*
                    #other_en
                }
            },
        ))
    }
}

// ── helpers ──────────────────────────────────────────────────

/// `a0, a1, …`: the payload values, bound by a pattern.
fn vars(n: usize) -> Vec<Ident> {
    (0..n).map(|i| format_ident!("a{i}")).collect()
}

/// `let [a0, a1] = args::<2>(tag, args)?;` and the decoded values.
fn tuple_de(items: &[Rs]) -> (TokenStream, Vec<TokenStream>) {
    let (vars, n) = (vars(items.len()), Literal::usize_unsuffixed(items.len()));
    let bind = quote!(let [#(#vars),*] = ::haus::de::args::<#n>(tag, args)?;);
    let values = items
        .iter()
        .zip(&vars)
        .enumerate()
        .map(|(i, (r, var))| {
            let (i, f) = (Literal::usize_unsuffixed(i), r.de.value());
            quote!(::haus::de::arg(tag, #i, #var, #f)?)
        })
        .collect();
    (bind, values)
}

/// The encoded payload values `a0`, `a1`, ….
fn tuple_en(items: &[Rs]) -> Vec<TokenStream> {
    items.iter().zip(vars(items.len())).map(|(r, var)| r.en.call(quote!(#var))).collect()
}

/// `let r = <record>?;`, then `r.closed(&["a", "b"])?;` for a closed record.
/// An open record without fields only has to be a record: `<record>?;`.
fn bind_record(record: TokenStream, closed: bool, fields: &[Field]) -> TokenStream {
    let keys = fields.iter().map(|f| &f.key);
    match (closed, fields.is_empty()) {
        (true, _) => quote! { let r = #record?; r.closed(&[#(#keys),*])?; },
        (false, true) => quote! { #record?; },
        (false, false) => quote! { let r = #record?; },
    }
}

/// `///` lines.
fn docs<'s>(lines: impl Iterator<Item = &'s str>) -> TokenStream {
    let lines = lines.map(|l| if l.is_empty() { String::new() } else { format!(" {l}") });
    quote!(#(#[doc = #lines])*)
}

/// `#[deprecated(note = "…")]` if the attributes say so (spec §14), or nothing.
fn deprecated(attrs: &[Attribute]) -> TokenStream {
    match deprecation(attrs) {
        Some(Some(note)) => quote!(#[deprecated(note = #note)]),
        Some(None) => quote!(#[deprecated]),
        None => quote!(),
    }
}

/// The parameters a type expression uses.
fn params_in<'a>(ty: &'a Ty, out: &mut HashSet<&'a str>) {
    match ty {
        Ty::Param { name, .. } => {
            out.insert(name);
        }
        Ty::Name { args, .. } => args.iter().for_each(|a| params_in(a, out)),
        Ty::Record { fields, .. } => fields.iter().for_each(|f| params_in(&f.ty, out)),
        Ty::Variant { cases, .. } => cases.iter().flat_map(|c| &c.payload).for_each(|t| params_in(t, out)),
    }
}

/// A type parameter: `a` → `A`, `elem` → `Elem`.
fn param(p: &str) -> Ident {
    format_ident!("{}", pascal(p))
}

/// `deliverTo` → `DeliverTo`, `pt-BR` → `PtBr`.
fn pascal(s: &str) -> String {
    s.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(|w| w[..1].to_ascii_uppercase() + &w[1..])
        .collect()
}

/// Keywords a field can't be called (`r#type` instead).
const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for", "gen",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct",
    "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
];

/// A field name in Rust: `deliverTo` → `deliver_to`, `type` → `r#type`, `pt-BR` → `pt_br`.
fn field_ident(key: &str) -> Ident {
    let snake = key.chars().enumerate().fold(String::new(), |mut out, (i, c)| {
        match c {
            c if c.is_ascii_uppercase() => {
                if i > 0 && !out.ends_with('_') {
                    out.push('_');
                }
                out.push(c.to_ascii_lowercase());
            }
            c if c.is_ascii_alphanumeric() || c == '_' => out.push(c),
            _ if !out.ends_with('_') => out.push('_'),
            _ => {}
        }
        out
    });
    match snake.as_str() {
        "" => format_ident!("_field"),
        // These can't be raw identifiers.
        "self" | "super" | "crate" => format_ident!("{snake}_"),
        s if s.starts_with(|c: char| c.is_ascii_digit()) => format_ident!("_{s}"),
        s if KEYWORDS.contains(&s) => Ident::new_raw(s, Span::call_site()),
        s => format_ident!("{s}"),
    }
}
