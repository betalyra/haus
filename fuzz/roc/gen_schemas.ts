/**
 * Generates the Roc package that the Roc runner of the schema fuzzer
 * (schema_runner.roc) decodes with: for each schema of test-suite/schema and
 * fuzz/schema, `haus-gen roc` writes the module NAME.roc (its types, decoders
 * and encoders), and Schemas.roc dispatches on the schema and type names.
 * Writes fuzz/.build/roc-schema/; run by fuzz/build.sh. Needs Rust (cargo).
 */
import { spawnSync } from "node:child_process"
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = new URL("../..", import.meta.url).pathname
const out = join(root, "fuzz/.build/roc-schema")
const dirs = [join(root, "test-suite/schema"), join(root, "fuzz/schema")]

const pascal = (s: string) => s.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("")

/** Like `snake` in rust/haus-build/src/roc.rs: `IntPair` → `int_pair`. */
function snake(s: string): string {
  let o = ""
  for (const [i, c] of [...s].entries()) {
    if (/[A-Z]/.test(c)) o += (i > 0 && !o.endsWith("_") ? "_" : "") + c.toLowerCase()
    else if (/[a-z0-9]/.test(c)) o += c
    else if (o && !o.endsWith("_")) o += "_"
  }
  return o
}

const roc = (s: string) => JSON.stringify(s).replace(/\$/g, "\\$")

mkdirSync(out, { recursive: true })
const schemas = dirs.flatMap((d) => readdirSync(d).filter((f) => f.endsWith(".schema.haus")).map((f) => join(d, f))).sort()
const modules: string[] = []
const suites: string[] = []
const codecs: string[] = []
for (const path of schemas) {
  const name = path.split("/").pop()!.replace(".schema.haus", "")
  const module = pascal(name)
  modules.push(module)
  const p = spawnSync("cargo", ["run", "-q", "--manifest-path", join(root, "rust/Cargo.toml"), "-p", "haus-build", "--bin", "haus-gen", "--", "roc", path, "--module", module, "--out", join(out, `${module}.roc`)], { encoding: "utf8" })
  if (p.status !== 0) throw new Error(`haus-gen roc ${path} failed: ${p.stderr}`)
  // The non-generic definitions are the types a case can name.
  const types = [...readFileSync(path, "utf8").matchAll(/^type\s+([A-Z][A-Za-z0-9_]*)\s*=/gm)].map((m) => m[1]!)
  suites.push(`\t\t${roc(name)} => ${snake(name)}(ty, v)\n`)
  codecs.push(
    `\t${snake(name)} : Str, Value -> Codec\n\t${snake(name)} = |ty, v| match ty {\n` +
      types.map((t) => `\t\t${roc(t)} => Decoded(${module}.decode_${snake(t)}(v).map_ok(${module}.encode_${snake(t)}))\n`).join("") +
      `\t\t_ => NoType\n\t}\n`,
  )
}
writeFileSync(join(out, "main.roc"), `# GENERATED by fuzz/roc/gen_schemas.ts. Do not edit.\npackage [Schemas, ${modules.join(", ")}] { haus: "../../../roc/package/main.roc" }\n`)
writeFileSync(
  join(out, "Schemas.roc"),
  `# GENERATED by fuzz/roc/gen_schemas.ts. Do not edit.
import haus.Value
import haus.Decode
${modules.map((m) => `import ${m}\n`).join("")}
Schemas := [].{
\t## The result of decoding a value with a type of a schema, encoded again.
\tCodec : [Decoded(Try(Value, Decode.Error)), NoType]

\t## Decode \`v\` with the type \`ty\` of the schema \`suite\`, and encode the result.
\troundtrip : Str, Str, Value -> Codec
\troundtrip = |suite, ty, v| match suite {
${suites.join("")}\t\t_ => NoType
\t}

${codecs.join("\n")}}
`,
)
console.log(`wrote ${out}: ${modules.join(", ")}`)
